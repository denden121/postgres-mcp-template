CREATE OR REPLACE FUNCTION api.sales_summary(date, date)
RETURNS TABLE(orders bigint, revenue numeric)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
BEGIN
 IF $1 IS NULL OR $2 IS NULL OR $2 < $1 OR $2 - $1 > 90 THEN
   RAISE EXCEPTION 'Invalid date range';
 END IF;
 RETURN QUERY SELECT count(DISTINCT o.id),coalesce(sum(i.quantity*i.unit_price),0)
 FROM private.orders o JOIN private.order_items i ON i.order_id=o.id
 WHERE o.status='paid' AND o.ordered_on BETWEEN $1 AND $2;
END $$;
CREATE OR REPLACE FUNCTION api.top_products(date,date,integer)
RETURNS TABLE(product text,revenue numeric)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
BEGIN
 IF $1 IS NULL OR $2 IS NULL OR $2 < $1 OR $2 - $1 > 90
 OR $3 IS NULL OR $3 < 1 OR $3 > 10 THEN
   RAISE EXCEPTION 'Invalid parameters';
 END IF;
 RETURN QUERY SELECT p.name,sum(i.quantity*i.unit_price) AS revenue
 FROM private.orders o JOIN private.order_items i ON i.order_id=o.id
 JOIN private.products p ON p.id=i.product_id
 WHERE o.status='paid' AND o.ordered_on BETWEEN $1 AND $2
 GROUP BY p.id,p.name ORDER BY revenue DESC,p.name LIMIT $3;
END $$;

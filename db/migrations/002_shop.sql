CREATE SCHEMA IF NOT EXISTS archive AUTHORIZATION data_owner;
SET ROLE data_owner;
CREATE TABLE private.customers (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL,
 email text NOT NULL UNIQUE
);
CREATE TABLE private.categories (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL UNIQUE,
 parent_id integer REFERENCES private.categories(id),
 CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE TABLE private.products (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_id integer NOT NULL REFERENCES private.categories(id),
 name text NOT NULL UNIQUE,
 price numeric(12,2) NOT NULL CHECK (price >= 0)
);
CREATE TABLE private.orders (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id integer NOT NULL REFERENCES private.customers(id),
 ordered_on date NOT NULL,
 status text NOT NULL CHECK (status IN ('paid','pending','cancelled'))
);
CREATE TABLE private.order_items (
 order_id integer NOT NULL REFERENCES private.orders(id),
 product_id integer NOT NULL REFERENCES private.products(id),
 quantity integer NOT NULL CHECK (quantity > 0),
 unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
 PRIMARY KEY (order_id, product_id)
);
CREATE TABLE private.payments (
 id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 order_id integer NOT NULL UNIQUE REFERENCES private.orders(id),
 amount numeric(12,2) NOT NULL CHECK (amount > 0),
 paid_on date NOT NULL,
 method text NOT NULL CHECK (method IN ('card','bank_transfer'))
);
